#!/usr/bin/env bash
# guardian-fapolicyd-setup.sh — correct, Arch-aware fapolicyd rollout for Guardian.
#
#   sudo packaging/fapolicyd/guardian-fapolicyd-setup.sh [--child-uid N]... [--enforce]
#
# Encodes exactly what the 2026-10-23 on-host test verified. Without args it reads the child uids from
# the guardiand drop-in (GUARDIAN_CHILD usernames) or defaults to uid 1001. It does NOT enforce unless
# you pass --enforce; the safe path is: run it (permissive), let the child use the machine, watch the
# log, then re-run with --enforce and REBOOT-TEST.
#
# Fixes folded in (IDs from guardian-fixes-2026-10-23.md):
#   C1  allow_filesystem_mark=1      — else bwrap/unshare bind-mounts run untrusted binaries
#   F1  trust.d in `path size sha256` — the real format; drop `\`/space paths or the load stops silently
#   F2  rules installed as 05-*       — before upstream 42/43 so they don't deny the parent/services
#   F3  Arch prereqs                  — fapolicyd user, trust=file, buildroot/ld_so/rpmdb quirks
#   F14 trust Guardian's own files    — wrappers + binaries aren't pacman-owned, so the child couldn't
#                                       even reach the install gate
set -euo pipefail
[ "$(id -u)" -eq 0 ] || { echo "run as root (sudo)"; exit 1; }
HERE="$(cd "$(dirname "$0")" && pwd)"

CONF=/etc/fapolicyd/fapolicyd.conf
RULES_D=/etc/fapolicyd/rules.d
TRUST_D=/etc/fapolicyd/trust.d
ENFORCE=0
CHILD_UIDS=()
while [ $# -gt 0 ]; do
  case "$1" in
    --child-uid) CHILD_UIDS+=("$2"); shift 2 ;;
    --enforce)   ENFORCE=1; shift ;;
    *) echo "unknown option: $1" >&2; exit 2 ;;
  esac
done

command -v fapolicyd >/dev/null 2>&1 || { echo "fapolicyd not installed — 'yay -S fapolicyd' first"; exit 1; }

# --- child uids ---------------------------------------------------------------
if [ "${#CHILD_UIDS[@]}" -eq 0 ]; then
  names="$(sed -nE 's/^Environment=GUARDIAN_CHILD=(.*)/\1/p' \
           /etc/systemd/system/guardiand.service.d/10-child.conf 2>/dev/null | tr -d '"' || true)"
  for n in $names; do u="$(id -u "$n" 2>/dev/null || true)"; [ -n "$u" ] && CHILD_UIDS+=("$u"); done
fi
[ "${#CHILD_UIDS[@]}" -eq 0 ] && CHILD_UIDS=(1001)
echo "==> child uids: ${CHILD_UIDS[*]}"

mkdir -p "$RULES_D" "$TRUST_D"

# --- F3: Arch prerequisites ---------------------------------------------------
echo "==> F3: Arch prerequisites"
# fapolicyd system user (the AUR package often doesn't create it)
getent passwd fapolicyd >/dev/null 2>&1 || systemd-sysusers 2>/dev/null || true
cp -a "$CONF" "$CONF.guardian.bak.$(date +%s)" 2>/dev/null || true
# rpmdb backend doesn't exist on Arch → file backend only
sed -i -E 's/^[[:space:]]*trust[[:space:]]*=.*/trust = file/' "$CONF"
grep -qE '^[[:space:]]*trust[[:space:]]*=' "$CONF" || echo "trust = file" >> "$CONF"
# 22-buildroot.rules references the RPM user `mock` and aborts fagenrules on Arch
if [ -f "$RULES_D/22-buildroot.rules" ]; then
  mv "$RULES_D/22-buildroot.rules" "$RULES_D/22-buildroot.rules.disabled"
  echo "    disabled 22-buildroot.rules (RPM user 'mock')"
fi
# 43-known-elf.rules can ship an unsubstituted %ld_so_path%
if [ -f "$RULES_D/43-known-elf.rules" ] && grep -q '%ld_so_path%' "$RULES_D/43-known-elf.rules"; then
  LDSO="$(ls /usr/lib/ld-linux-x86-64.so.* 2>/dev/null | head -1)"
  [ -n "$LDSO" ] && sed -i "s#%ld_so_path%#$LDSO#g" "$RULES_D/43-known-elf.rules" \
    && echo "    substituted %ld_so_path% → $LDSO"
fi

# --- C1: watch namespace bind mounts -----------------------------------------
echo "==> C1: allow_filesystem_mark = 1 (blocks bwrap/unshare bind-mount laundering)"
if grep -qE '^[[:space:]]*allow_filesystem_mark' "$CONF"; then
  sed -i -E 's/^[[:space:]]*allow_filesystem_mark[[:space:]]*=.*/allow_filesystem_mark = 1/' "$CONF"
else
  echo "allow_filesystem_mark = 1" >> "$CONF"
fi

# --- rules (F2: 05- so they precede upstream 42/43) ---------------------------
echo "==> installing rules as $RULES_D/05-guardian.rules (multi-child)"
{
  echo "# generated by guardian-fapolicyd-setup.sh — do not edit by hand (see 05-guardian.rules template)"
  echo "allow perm=any uid=0 : all"
  for u in "${CHILD_UIDS[@]}"; do
    echo "deny_audit perm=execute pattern=ld_so uid=$u : all"
    echo "deny_audit perm=execute uid=$u : all trust=0"
    echo "allow      perm=execute uid=$u : all trust=1"
    echo "deny_audit perm=open uid=$u : all ftype=application/x-sharedlib trust=0"
  done
  echo "allow perm=any all : all"
} > "$RULES_D/05-guardian.rules"
# the shipped 50-name must not also be present (old installs)
rm -f "$RULES_D/50-guardian.rules"

# --- F1: seed trust from pacman in the correct `path size sha256` format -------
SEED="$TRUST_D/pacman"
echo "==> F1: seeding trust from pacman into $SEED (hashing every package file — this is slow)"
: > "$SEED"
while IFS= read -r f; do
  case "$f" in *\\*|*' '*) continue ;; esac          # a backslash/space path silently stops the load
  [ -f "$f" ] || continue
  sum="$(sha256sum "$f" 2>/dev/null)" || continue
  sz="$(stat -c %s "$f" 2>/dev/null)" || continue
  printf '%s %s %s\n' "$f" "$sz" "${sum%% *}"
done < <(pacman -Qlq) >> "$SEED"
echo "    wrote $(wc -l < "$SEED") trusted files"

# --- F14: trust Guardian's own (non-pacman) files -----------------------------
echo "==> F14: trusting Guardian's own files"
for f in /usr/local/bin/flatpak /usr/local/bin/snap /usr/local/bin/nix-env \
         /usr/bin/guardian-ctl /usr/bin/guardian-sign /usr/bin/guardiand \
         /usr/lib/guardian/guardian-hook /usr/lib/guardian/guardian-trust \
         /usr/lib/guardian/guardian-lock /usr/lib/guardian/guardian-unlock \
         /usr/lib/guardian/guardian-watchdog; do
  [ -e "$f" ] || continue
  tgt="$(readlink -f "$f")"                            # /usr/local/bin/nix is a symlink
  fapolicyd-cli --file add "$tgt" --trust-file guardian >/dev/null 2>&1 \
    && echo "    + $tgt"
done

# --- load + verify ------------------------------------------------------------
echo "==> compiling rules + loading trust"
fagenrules --load >/dev/null 2>&1 || true
fapolicyd-cli --update >/dev/null 2>&1 || true

SEEDN="$(wc -l < "$SEED")"
DBN="$(fapolicyd-cli --dump-db 2>/dev/null | wc -l || echo 0)"
echo "==> trust DB has $DBN entries; pacman seed had $SEEDN"
if [ "$DBN" -lt $((SEEDN * 9 / 10)) ]; then
  echo "    !! DB is well below the seed — a path probably stopped the load. Do NOT enforce yet."
  echo "       Check:  journalctl -u fapolicyd | grep -i 'without duplicates'"
fi

if [ "$ENFORCE" -eq 1 ]; then
  echo "==> ENFORCING: enabling fapolicyd"
  systemctl enable --now fapolicyd
  echo "    Verify as the child:  bwrap --dev-bind / / --bind ~/x /usr/bin/true /usr/bin/true  → Operation not permitted"
  echo "    *** REBOOT-TEST NOW *** — a bad trust DB only bites on the next boot."
else
  cat <<'PERM'
==> SET UP (not enforcing). Test permissive first, keeping a ROOT shell open:
      sudo fapolicyd --debug --permissive 2>&1 | tee /tmp/fap.log   # Ctrl-C to stop
    Have the child use the machine; grep /tmp/fap.log for legit "would deny" and add them to trust.
    When the log is clean, enable enforcing + REBOOT-TEST:
      sudo packaging/fapolicyd/guardian-fapolicyd-setup.sh --enforce
    Roll back instantly:  sudo systemctl stop fapolicyd
PERM
fi
